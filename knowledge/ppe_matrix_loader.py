def load() -> int:
    conn = connect()
    conn.executescript(DDL)
    n = 0
    for wt, marks in M.items():
        for item in ITEMS:
            mk = marks.get(item, "")
            if not mk:
                continue
            conn.execute("INSERT OR REPLACE INTO ppe_work_matrix(work_type,item,mark,source) "
                         "VALUES(?,?,?,?)", (wt, item, mk, SRC))
            n += 1
    conn.commit()
    conn.close()
    return n


def matrix_from_db() -> tuple[list[str], list[str], dict[str, dict[str, str]]]:
    """→ (work_types, items, {work_type: {item: mark}}) — 供 section_filler 出表"""
    conn = connect()
    rows = conn.execute("SELECT work_type, item, mark FROM ppe_work_matrix "
                        "ORDER BY id").fetchall()
    conn.close()
    wts, items, out = [], [], {}
    for wt, item, mk in rows:
        if wt not in wts:
            wts.append(wt)
        if item not in items:
            items.append(item)
        out.setdefault(wt, {})[item] = mk
    return wts, items, out


def matrix_table(name: str) -> dict | None:
    """出与原报告逐字一致的矩阵表 dict

    行序=WORK_TYPES (原报告作业类型序), 列序=ITEMS (原报告装备列序) — 固定序,
    不随 DB 出现序漂移; 表头显示文本取 ITEMS_DISP (原报告取证换行).
    """
    _wts, _items, m = matrix_from_db()
    if not m:
        return None
    wts = [wt for wt in M if wt in m]
    cols = [FIRST_COL] + [ITEMS_DISP.get(it, it) for it in ITEMS]
    rows = [[wt] + [m.get(wt, {}).get(it, "") for it in ITEMS] for wt in wts]
    return {"name": name, "cols": cols, "rows": rows}


