def plan_grade(category, dims=()) -> dict:
    """(库里的类别, 该因子接触限值行的量纲文本) → 该走 229 的哪一部分、用哪个引擎。

    纯函数, 不碰库 —— 所以 tools/test_grade_routing.py 能在合成数据上跑完整真值表。
    返回 {"engine": "dust|chemical|heat|noise|None", "part": str|None, "reason": str};
    reason 非空 = **不定级**, 调用方必须把它原样放进输出的"依据"列, 不许丢。
    """
    cat = str(category or "").strip()
    if cat not in CATEGORY_ROUTING:
        tail = f"（类别字段={cat!r}）" if cat else "（类别字段为空）"
        return {"engine": None, "part": None, "reason": UNCLASSIFIED_HOLD + tail}
    engine, part, hold = CATEGORY_ROUTING[cat]
    if engine != "physical":
        return {"engine": engine, "part": part, "reason": hold}
    dim_text = " ".join(str(x) for x in (dims or ())).lower()
    for keys, eng, p, r in DIMENSION_ROUTING:
        if any(k in dim_text for k in keys):
            return {"engine": eng, "part": p, "reason": r}
    return {"engine": None, "part": None, "reason": PHYS_NO_PART_HOLD}


# ---- 229.2 化学物分级 ----
def grade_chemical(wd_level: str, b: float, labor: str) -> dict:
    """化学物作业分级: G = WD×WB×WL (229.2 式4/表5)
    wd_level: 轻度危害/中度危害/高度危害/极度危害 (GBZ/T 230)
    b: 接触比值 C/PC-TWA (或CSTE/PC-STEL, CME/MAC)
    labor: 体力劳动强度 Ⅰ/Ⅱ/Ⅲ/Ⅳ

    常数核对 (#39, pdf_cells 逐格, GBZ_T_229.2_2025.pdf): WD 表1=第4页第1张表 r1-r4
    ['轻度危害','1'] ['中度危害','2'] ['高度危害','4'] ['极度危害','8'] ✓;
    WB 表2=第4页第2张表 r1 ['B≤0.5','0'] r2 ['B＞0.5','B'] ✓ (粉尘不是这条分界, 见 grade_dust);
    WL 表3=第5页第1张表 r1-r4 (1.0/1.5/2.0/2.5) ✓;
    式(4) 与级别=第6页正文 + 第8页第1张表 r1-r4 (G=0→0级 / 0＜G≤6→Ⅰ / 6＜G≤24→Ⅱ / G＞24→Ⅲ) ✓;
    "B>1 强制≥Ⅱ" = 第8页表5 末行注 ['注：若B＞1 则为Ⅱ级（中度危害作业）或以上作业。'] ✓
    → 化学物这一支**与原文一致, 未改动数值**, 改动只发生在路由 (别再从这里领走粉尘)。"""
    wd = WD_TABLE.get(wd_level, 4)     # 缺省按高度危害(保守)
    wb = 0 if b <= 0.5 else b
    wl = WL_TABLE.get(labor, 1.5)
    g = wd * wb * wl
    if g == 0:
        level, name = "0", "相对无害作业"
    elif g <= 6:
        level, name = "Ⅰ", "轻度危害作业"
    elif g <= 24:
        level, name = "Ⅱ", "中度危害作业"
    else:
        level, name = "Ⅲ", "重度危害作业"
    # 注: B>1 则为Ⅱ级或以上
    if b > 1 and level == "Ⅰ":
        level, name = "Ⅱ", "中度危害作业"
    return {"g": round(g, 2), "wd": wd, "wb": wb, "wl": wl,
            "level": level, "name": name,
            "note": "G=WD×WB×WL (229.2 式4/表5)" if not (b > 1 and level == "Ⅱ")
                    else "B>1强制≥Ⅱ级 (表5注)"}


# ---- 229.1 粉尘分级 ----
def grade_dust(sio2_band: str, b: float, labor: str) -> dict:
    """粉尘作业分级: G = WM×WB×WL (229.1 式1), 级别按表4 的五级
    sio2_band: 游离SiO2含量(M)的分档键 <10 / 10-50 / 50-80 / >80 (229.1 表1)
    b: 职业接触限值比值 CTWA/PC-TWA (式 A.1)
    labor: 体力劳动强度
    → 分档键取不到 WM 时返回 **None**: 旧实现这里 `WM_TABLE.get(band, 4)` 默默兜到最坏档,
      而 4 在新表里既不是一档 (1/2/4/6 中的 4 是 50＜M≤80), 也不表示"不知道" ——
      "不知道 M"就定不了级, 调用方必须把 None 变成一句看得见的"未定级 + 原因"。

    常数核对 (#39, pdf_cells 逐格, GBZ_T_229.1_2025.pdf, 按 span 原样顺序取字):
      第4页 表1 (WM) = 该页第1张表: r1 ['M＜10','1'] r2 ['10≤M≤50','2']
        r3 ['50＜M≤80','4']  ← 代码原来写 3  (已按原文改)
        r4 ['M＞80','6']     ← 代码原来写 4  (已按原文改)
        50-80/>80 从 3/4 改成 4/6 会把矽尘类作业**升 1~2 级**, 旧值是系统性低估。
      第4页 表2 (WB) = 该页第2张表: r1 ['B≤1','0'] r2 ['B＞1','B']
        ← 代码原来抄了 229.2 表2 的 0.5 分界。差别落在 0.5＜B≤1 这一段: 原文 WB=0 → G=0,
        再由表4 第2行判成 Ⅰ级(行动水平作业); 旧写法 WB=B>0 → 直接算成 Ⅱ级(轻度危害),
        而且让表4 第2行那条 Ⅰ级在代码里变成**永远走不到的死分支**。
      第5页 表4 (级别) = 该页第2张表: r1 ['G=0 且B≤0.5','0 级（相对无害作业）']
        r2 ['G=0 且B＞0.5','Ⅰ级（行动水平作业）'] r3 ['0＜G≤6','Ⅱ级（轻度危害作业）']
        r4 ['6＜G≤16','Ⅲ级（中度危害作业）'] r5 ['G＞16','Ⅳ级（高度危害作业）']
        → 阈值 6/16 与代码一致 ✓, 级别名一致 ✓
      第4-5页 表3 (WL) 1.0/1.5/2.0/2.5 ✓ (与 229.2 表3 同值)
      第6页 表5 是"直接查表"版 (4.4.3: 跨级者应采用计算方法确定分级) → 本函数按式(1)+表4,
        不复制表5 (表5 的 Ⅱ～Ⅲ 跨格用计算表达更准, 也不会多维护一张会腐烂的表)。"""
    if sio2_band not in WM_TABLE:
        return None
    wm = WM_TABLE[sio2_band]
    wb = 0 if b <= 1 else b           # 229.1 表2: B≤1 → WB=0 (与 229.2 的 0.5 分界**不同**)
    wl = WL_TABLE.get(labor, 1.5)
    g = wm * wb * wl
    if g == 0 and b <= 0.5:
        level, name = "0", "相对无害作业"
    elif g == 0:
        level, name = "Ⅰ", "行动水平作业"
    elif g <= 6:
        level, name = "Ⅱ", "轻度危害作业"
    elif g <= 16:
        level, name = "Ⅲ", "中度危害作业"
    else:
        level, name = "Ⅳ", "高度危害作业"
    return {"g": round(g, 2), "wm": wm, "wb": wb, "wl": wl, "sio2_band": sio2_band,
            "level": level, "name": name, "note": "G=WM×WB×WL (229.1 式1/表1/表4)"}


