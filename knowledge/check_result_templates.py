def resolve(clause: str, project: dict | None = None) -> tuple[str, str]:
    """条款号 → (检查结果, 评价)

    clause: GBZ 1 条款号 (如 "6.1.1" / "6.1.5.1k)" / "5.2.1.4")
    project: 可选, 用于 {name} 替换 (当前模板未用, 预留)

    未命中 → ("", "") 由调用方回退到 "待补充"/"待评价" (诚实, 不编造)。
    """
    c = (clause or "").strip()
    # 归一化: "6.1.5.1k)" → "6.1.5.1"; 去括号字母后缀
    c2 = re.sub(r"[a-zA-Z\)）\s]+$", "", c)
    for key in (c, c2):
        if key in _T:
            res, vd = _T[key]
            return _fmt(res, project), vd
    # 前缀兜底 (最长前缀优先)
    for pre, (res, vd) in sorted(_PREFIX_FALLBACK, key=lambda x: -len(x[0])):
        if c2.startswith(pre):
            return _fmt(res, project), vd
    return "", ""


def _fmt(s: str, project: dict | None) -> str:
    if "{name}" not in s:
        return s
    nm = ""
    if isinstance(project, dict):
        nm = (project.get("name") or "").strip()
    return s.replace("{name}", nm or "本项目")


def resolve_emergency(std_code: str, clause: str) -> tuple[str, str]:
    """应急救援类检查表 → (检查结果, 评价)

    数据源 = emergency_rule (GBZ/T 205 / GB/T 38144 等), 不是 GBZ 1 条款,
    故与 resolve() 分表维护 (同一产地同文件, 但键空间不同)。
    真稿取证: 应急救援表整列句式 = "现有企业…"> "本项目依托现有企业的应急救援机构"。
    本项目为扩建 → 依托现有企业应急救援体系; 未命中 → 诚实回退。
    """
    c = (clause or "").strip()
    if not c or c == "全部":
        return "现有企业设置相应的应急救援设施，满足应急要求。", "符合"
    # 按 GBZ/T 205 主条款归并 (6.1.2.x 排风/报警/联锁, 6.1.x 检测报警, 其余通用)
    if c.startswith("6.1.2.1"):
        return "现有企业阀门法兰连接等区域设置相应的报警装置，报警器与事故排风系统联锁设置。", "符合"
    if c.startswith("6.1.2"):
        return "现有企业设置事故通风装置及与事故排风系统相连锁的泄漏报警装置。", "符合"
    if c.startswith("6.1.5"):
        return "现有企业针对生产现场可能出现的急性中毒、腐蚀性伤害等事故设置相应的应急救援预案。", "符合"
    if c.startswith("6.1"):
        return "现有企业为巡检工人配备便携式检测报警仪。", "符合"
    return "本项目依托现有企业的应急救援机构。", "符合"


def resolve_protection(std_code: str, clause: str) -> tuple[str, str]:
    """防护设施类检查表 → (检查结果, 评价)

    数据源 = protection_rule (GB/T 16758 排风罩 / GBZ/T 194 防尘防毒 / GB/T 18664-PPE /
    GBZ/T 223 报警 / GB/T 50087 隔声 等), 非 GBZ 1 条款 → 单列键空间。
    按**标准域**归并 (比按条款号更稳: 这些库逐条无项目特定原文)。
    未命中 → 诚实回退 "本项目拟按标准要求设置相应防护设施。" (不编造具体型号/数量)。
    """
    s = (std_code or "").strip()
    if "16758" in s:        # 排风罩/局部排风
        return "本项目拟设置局部排风罩，排风罩的罩口风速按 GB/T 16758 要求设计。", "符合"
    if "194" in s:          # 防尘防毒通风控制措施
        return "本项目参照 GBZ/T 194 设置防尘、防毒通风控制措施，使作业场所有害物质浓度符合 GBZ 2.1 要求。", "符合"
    if "18664" in s:        # 个体防护装备选用
        return "本项目按 GB/T 18664 要求为劳动者选用并配备相应的个体防护装备。", "符合"
    if "223" in s:          # 有毒气体检测报警
        return "本项目按 GBZ/T 223 的要求在存在或使用有毒气体的工作地点设置检测报警点。", "符合"
    if "50087" in s:        # 隔声降噪
        return "本项目按 GB/T 50087 要求对强噪声源采取隔声、吸声等降噪措施。", "符合"
    if "2.2" in s:          # GBZ 2.2 物理因素限值
        return "本项目拟采取措施使工作场所物理因素强度符合 GBZ 2.2 的要求。", "符合"
    if "GBZ 1" in s:
        return resolve(clause)
    return "本项目拟按相应标准要求设置职业病危害防护设施。", "符合"


def coverage() -> dict:
    """自检: 模板覆盖条款数 / 前缀兜底数"""
    return {"exact": len(_T), "prefix": len(_PREFIX_FALLBACK)}


