# ── 节标题判定 (2026-10-08 修): outlineLvl 优先, 正则兜底 ──────────────────
# ⚠ 旧版只看「数字开头且<60字」→ 正文内列举项「1）……」「1、反应方程式」被误判为
#   节标题 → 真稿 5.6 受限空间被切成 43 字(实际 1631 字), 字数比虚报 2477%。
#   新正则要求编号后紧跟 空格/中文/引号/书名号 (排除「1）」这种标点跟随后续是长句的)。
_NUMH = re.compile(r'^(\d+(?:\.\d+)*)(?=[\s\u4e00-\u9fff“”《])\s*(\S.*)?$')


def _heading_num(el, t):
    """返回节编号; 非节标题返回 None。有 outlineLvl 即标题(最可靠判据)。"""
    pPr = el.find(W + 'pPr')
    if pPr is not None and pPr.find(W + 'outlineLvl') is not None:
        m = _NUMH.match(t)
        return m.group(1) if m else None
    m = _NUMH.match(t)
    if m and len(t) < 60 and m.group(2):
        return m.group(1)
    return None


def load(path):
    z = zipfile.ZipFile(path)
    x = etree.fromstring(z.read('word/document.xml'))
    body = x.find(W + 'body')
    out, cur = [], None
    for el in body:
        tag = etree.QName(el).localname
        if tag == 'p':
            t = ''.join(n.text or '' for n in el.iter(W + 't')).strip()
            num = _heading_num(el, t) if t else None
            if num:
                if cur:
                    out.append(cur)
                cur = [num, t, 0, 0]
            elif cur is not None:
                cur[2] += len(t)
        elif tag == 'tbl':
            n = sum(len(nn.text or '') for nn in el.iter(W + 't'))
            if cur is not None:
                cur[3] += n
    if cur:
        out.append(cur)
    return out


def subtree(rows, num, self_only=False):
    """num 及其后代 (num.1 / num.1.2 ...) 的 段落+表格 合计

    num 末尾带 '@' → 只取该节点自身, 不含子孙 (与 self_only=True 等效)。
    真稿层级与生成稿不一致时用 (如 8.1.2建设地点 vs 8.1.2.1自然环境概况)。

    返回 (段落数, 表格数, 自身数, 含子数):
      自身 = 该节点标题下的直属段落+表格
      含子 = 自身 + 所有后裔
    """
    if num.endswith('@'):
        self_only = True
        num = num[:-1]
    pre = num + '.'
    own_p = own_t = sub_p = sub_t = 0
    for n, _t, pp, tt in rows:
        if n == num:
            own_p += pp
            own_t += tt
        elif n.startswith(pre):
            sub_p += pp
            sub_t += tt
    if self_only:
        return own_p, own_t, own_p + own_t, own_p + own_t
    return own_p, own_t, own_p + own_t, own_p + own_t + sub_p + sub_t


def main():
    gen = sys.argv[1] if len(sys.argv) > 1 else 'data/report_ada54603a9.docx'
    real = sys.argv[2] if len(sys.argv) > 2 else '/tmp/rec16_conv/长兴--预评（备案稿7-31）.docx'
    G, R = load(gen), load(real)

    print(f"{'生成稿节':<9}{'标题':<22}{'生成':>7}{'真稿':>7}{'生成自身':>9}{'真稿自身':>9}  判定")
    print('-' * 82)
    miss, thin, ok, na = [], [], [], []
    for gnum, name, rnum, note in PAIRS:
        _, _, g_own, g_all = subtree(G, gnum)
        gv = g_all
        if rnum is None:
            print(f"{gnum:<9}{name[:20]:<22}{gv:>7}{'—':>7}{g_own:>9}{'—':>9}  ✚新增")
            na.append((name, gv))
            continue
        r_own = r_all = 0
        for rn in rnum.split('/'):
            _, _, ro, ra = subtree(R, rn.strip())
            r_own += ro
            r_all += ra
        rv = r_all
        if rv == 0 and gv == 0:
            verdict = "—空"
        elif gv == 0:
            verdict = "❌生成缺"
            miss.append((name, rv, note))
        elif rv == 0:
            verdict = "·真稿无"
        elif gv < rv * 0.5:
            verdict = f"⚠{gv/rv:.0%}"
            thin.append((name, rv, gv, note, r_own, g_own))
        else:
            verdict = f"✓{gv/rv:.0%}"
            ok.append(name)
        print(f"{gnum:<9}{name[:20]:<22}{gv:>7}{rv:>7}{g_own:>9}{r_own:>9}  {verdict}")

    print(f"\n=== ✓{len(ok)} / ⚠偏薄{len(thin)} / ❌缺失{len(miss)} / ✚新增{len(na)} ===")
    if miss:
        print("\n❌ 真稿有、生成缺:")
        for n, v, note in miss:
            print(f"   {n:<26} 真稿 {v} 字   {note}")
    if thin:
        print("\n⚠ 偏薄(<50%) — 分两口径看:")
        print(f"   {'节':<26}{'真稿自身':>9}{'生成自身':>9}  说明")
        for n, r, g, note, r_own, g_own in sorted(thin, key=lambda x: x[2] / x[1]):
            tip = ""
            if r_own == 0 and r > 0:
                tip = "真稿内容在子节 → 比『含子』"
            elif g_own == 0 and g > 0:
                tip = "生成内容在子节 → 父节是壳, 不算薄"
            elif r_own and g_own and g_own >= r_own * 0.5:
                tip = "★自身不缺(字差在表/子节)"
            else:
                tip = "★真缺内容"
            print(f"   {n:<26}{r_own:>9}{g_own:>9}  {tip}")


if __name__ == '__main__':
    main()
