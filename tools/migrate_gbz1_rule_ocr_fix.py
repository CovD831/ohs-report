def scan(db_path, apply=False):
    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row
    nf = nd = nm = 0
    logs = []
    for i, clause, old, new in CHANGES:
        row = conn.execute("SELECT rule, verified FROM gbz1_rule WHERE id=?", (i,)).fetchone()
        if row is None:
            nm += 1
            logs.append("[MISS] id=%d (%s) 行不存在" % (i, clause))
            continue
        if row["verified"] != 0:
            nm += 1
            logs.append("[GUARD] id=%d (%s) verified=1 拒绝修改" % (i, clause))
            continue
        cur = row["rule"]
        if cur == old:
            nf += 1
            logs.append("[FIX] id=%d (%s)" % (i, clause))
            if apply:
                c2 = conn.execute(
                    "UPDATE gbz1_rule SET rule=? WHERE id=? AND rule=? AND verified=0",
                    (new, i, old))
                if c2.rowcount != 1:
                    logs.append("  !! UPDATE rowcount=%d" % c2.rowcount)
        elif cur == new:
            nd += 1
            logs.append("[DONE] id=%d (%s) 已迁移" % (i, clause))
        else:
            nm += 1
            logs.append("[MISS] id=%d (%s) 现值非 old 非 new: %r" % (i, clause, cur[:60]))
    if apply:
        conn.commit()
    conn.close()
    return nf, nd, nm, logs


def main():
    argv = sys.argv[1:]
    apply = "--apply" in argv
    db_path = DEFAULT_DB
    if "--db" in argv:
        db_path = Path(argv[argv.index("--db") + 1])
    nf, nd, nm, logs = scan(db_path, apply=apply)
    summary = "%s db=%s FIX=%d DONE=%d MISS=%d" % (
        "APPLY" if apply else "DRY-RUN", db_path, nf, nd, nm)
    print(summary)
    out = Path("/tmp/migrate_gbz1_rule_out.txt")
    out.write_text(summary + "\n" + "\n".join(logs) + "\n", encoding="utf-8")
    print("明细: %s" % out)
    if nm:
        sys.exit(2)


if __name__ == "__main__":
    main()
