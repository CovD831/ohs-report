# 三级单元: 由数据驱动 (物质/工序/岗位/设备), 标题=单元名. 这里只给规则, 不硬编码.


def section_title(sec: str) -> str:
    return CHAPTERS.get(sec, sec)


def sub_title(sub: str) -> str:
    """sub 形如 '2.1' 或 '1.2' → 标题"""
    if "." in sub:
        ch, n = sub.split(".", 1)
        for sn, t in SUBS.get(ch, []):
            if sn == sub:
                return t
    return sub


def all_units() -> list[tuple]:
    """返回 (key, title) 列表: 各级章节. key 供 section_states 用."""
    units = []
    for ch in "123456789":
        units.append((ch, CHAPTERS[ch]))
        for sn, t in SUBS.get(ch, []):
            units.append((sn, f"{sn} {t}"))
    return units
