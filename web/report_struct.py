def sub_title(sub: str) -> str:
    """sub 形如 '2.1' → 标题"""
    if "." in sub:
        ch, n = sub.split(".", 1)
        for sn, t in SUBS.get(ch, []):
            if sn == sub:
                return t
    return sub


def sub3_title(sub3: str) -> str:
    """sub3 形如 '2.1.1' → 标题"""
    return SUBS3.get(sub3, (None, sub3))[1]


def sub4_title(sub4: str) -> str:
    """固定四级标题 (SUBS4 查)"""
    for parent, items in SUBS4.items():
        for num, t in items:
            if num == sub4:
                return t
    return sub4


def _extract_product_units(proj_data: dict) -> list[tuple]:
    """从项目数据提取产品/工段名, 生成数据驱动四级标题 (8.4.1.x / 10.1.1.x)

    真实报告四级 = 产品/工段/系统级 (特殊单体、垃圾焚烧发电、烟气净化系统),
    不是物质级. 来源: 设备名、工艺文本关键词.
    返回 [(四级编号, 标题)], 如 [('8.4.1.1','特殊单体'), ('8.4.1.2','齐聚物')]
    """
    import re
    items = []
    # 1) 从设备名提取产品/工段 (设备名常含产品线, 如'特殊单体R27&R28生产线')
    eqs = proj_data.get("equipment", []) or []
    seen = set()
    for e in eqs:
        name = str(e).split("|")[0].strip()
        if not name:
            continue
        # 去掉'生产线/装置/设备/系统'等尾缀, 提取产品名
        m = re.match(r"^(.{2,20}?)(?:生产线|装置|系统|车间|单元|机组)", name)
        if m:
            prod = m.group(1).strip()
            if prod and prod not in seen and len(prod) >= 2:
                items.append(prod)
                seen.add(prod)
    # 2) 从工艺文本补充 ('- 车间 X | 工序 Y' 里的 X 工段名)
    for ln in (proj_data.get("process_text") or "").splitlines():
        m = re.match(r"- 车间\s*(\S+)", ln.strip())
        if m and m.group(1) not in seen and len(m.group(1)) >= 2:
            items.append(m.group(1))
            seen.add(m.group(1))
    # 去重保序, 最多 8 个 (控制四级规模)
    items = list(dict.fromkeys(items))[:8]
    # 生成 8.4.1.x 和 10.1.1.x 两级列表 (同一产品/工段在两个三级下各一个四级)
    out = []
    for i, name in enumerate(items, 1):
        out.append((f"8.4.1.{i}", f"{name}生产工艺流程"))
        out.append((f"10.1.1.{i}", f"{name}"))
    return out


def count_units(proj_data: dict | None = None) -> int:
    """统计报告全部生成单元数 (章 + 二级 + 三级 + 固定四级 + 数据四级), 供进度 total"""
    n = 0
    for ch in CHAPTERS:
        n += 1                              # 该章
        for sn, _t in SUBS.get(ch, []):
            n += 1                          # 二级
            for sub3, (parent, _t3) in SUBS3.items():
                if parent == sn:
                    n += 1                  # 三级
                    n += len(SUBS4.get(sub3, []))   # 固定四级
    if proj_data:
        n += len(_extract_product_units(proj_data)) # 数据四级
    return n


def all_units() -> list[tuple]:
    """返回报告全部结构单元 (key, title): 一级 + 二级 + 三级 + 固定四级.
    数据四级(产品/工段)由生成时从项目数据补充, 不在此列表."""
    units = []
    for ch in CHAPTERS:
        units.append((ch, CHAPTERS[ch]))
        for sn, t in SUBS.get(ch, []):
            units.append((sn, f"{sn} {t}"))
            # 三级
            for sub3, (parent, t3) in SUBS3.items():
                if parent == sn:
                    units.append((sub3, f"{sub3} {t3}"))
                    # 四级挂在三级下 (SUBS4 key 是三级编号)
                    for num, t4 in SUBS4.get(sub3, []):
                        units.append((num, f"{num} {t4}"))
    return units


