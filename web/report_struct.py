def _extract_product_units(proj_data: dict) -> list[tuple]:
    """从项目数据提取产品/工段名, 生成数据驱动三级/四级标题

    真实报告: 三级 3.5.x = 各产品工艺 (氯化钙生产工艺); 四级 5.1.1.x = 各产品/工段识别.
    来源: 设备名、工艺文本关键词、产品产量表.
    返回 [(编号, 标题)], 如 [('3.5.1','氯化钙生产工艺'), ('3.5.2','氟化盐生产工艺'),
                          ('5.1.1.1','氯化钙'), ('5.1.1.2','氟化盐')]
    """
    import re
    items = []
    seen = set()
    # 0) 本项目产品判定: 产品表有"变化量"列 → 变化量>0 的行才是本项目产品
    #    (扩建项目产品表=全厂产品(存量+新增), 如长兴[通用型+12000/饱和+0]; 项目只新增12000通用型)
    #    新建项目无变化量列 → 全部产品都是本项目产品
    reduced = []
    has_delta = any(isinstance(p, dict) and p.get("delta_num") is not None
                    for p in (proj_data.get("products") or []))
    if has_delta:
        for p in (proj_data.get("products") or []):
            if isinstance(p, dict) and (p.get("delta_num") or 0) > 0:
                reduced.append(p)
        if reduced:  # 有变化量>0的产品 → 用本项目产品; 全0(没新增)则全部(兜底)
            prods_src = reduced
        else:
            prods_src = proj_data.get("products") or []
    else:
        prods_src = proj_data.get("products") or []
    # 1) 产品产量表 (最可靠: 产品名/工段名)
    for p in prods_src:
        if isinstance(p, dict):
            name = str(p.get("name") or p.get("产品名称") or p.get("product") or "").strip()
        else:
            name = str(p).split("|")[0].strip()
        name = re.sub(r"[（(].*?[)）]", "", name).strip()  # 去括号(产能/规格)
        # 去重: 同前缀(氯化钾 vs 氯化钾水溶液; 氢氟酸 vs 氢氟酸30%) → 只保留短的(通用名)
        # (修复: 新泰产品表含"氯化钾"(0)与"氯化钾水溶液"(17000)为同一产品 → 重复单元)
        if name and len(name) >= 2:
            dup = False
            for it in items:
                if name == it or (len(it) >= 2 and (it.startswith(name) or name.startswith(it))):
                    dup = True
                    break
            if not dup:
                items.append(name)
                seen.add(name)
    # 1.5) 项目名称匹配产品线 (通用: 项目名含产品名 → 只保留相关产品)
    #      (修复: 新泰'液体氯化钙、氢氟酸及氯化钾溶液产品结构调整项目' 产品表=全厂21条,
    #       但项目只涉'氯化钙/氢氟酸(氟化盐)/氯化钾' → 原报告3.5只4条; 长兴'不饱和聚酯树脂扩建'→1条)
    #      规则: 项目名提取产品关键词, 产品表命中则只用命中产品 (≥1命中才限定, 新建项目名不含产品→全量)
    proj_name = str(proj_data.get("name") or proj_data.get("指标值") or "")
    name_products = []
    for m in re.finditer(r"([\u4e00-\u9fa5A-Za-z0-9]{1,12}?(?:树脂|氯化钙|氢氟酸|氯化钾|氯化钠|盐酸|磷酸|硫酸|硝酸|氟化盐|氟化氢|氢氧化钠|氢氧化钾|碳酸钠|碳酸钙|氟化氢|聚酯|聚氨酯|丙烯酸|沥青|溶剂油|合成树脂|单体))", proj_name):
        name_products.append(m.group(1))
    # 拆词: "液体氯化钙" → ["氯化钙"]; "氢氟酸及氯化钾" → ["氢氟酸","氯化钾"] (按、及和与 拆)
    _split = re.compile(r"[、及和与，,]")
    _split_products = []
    for np_ in name_products:
        npc = np_.replace("（", "").replace("）", "")
        npc = re.sub(r"^(?:液体|固体|混合|年产|溶液|产品|新建|扩建|技改|改造|新增|调整|复合)", "", npc)
        for seg in _split.split(npc):
            if seg and len(seg) >= 2 and seg not in _split_products:
                _split_products.append(seg)
    name_products = _split_products or name_products
    if name_products and items:
        keep = set()
        # 别名映射: 项目名产品词 → 产品表可能用的同义词 (通用, 非单项目)
        ALIAS = {"氢氟酸": ("氟化盐", "氟化氢"), "氟化氢": ("氟化盐", "氢氟酸"),
                 "氟化盐": ("氟化氢", "氢氟酸"),
                 "氯化钙": ("氯化钙",), "氯化钾": ("氯化钾",), "氯化钠": ("氯化钠",),
                 "氢氧化钠": ("氢氧化钠", "烧碱"), "氢氧化钾": ("氢氧化钾", "苛性钾"),
                 "聚酯": ("聚酯", "树脂"), "树脂": ("树脂", "聚酯")}
        for it in items:
            for np_ in name_products:
                npc = np_.replace("（", "").replace("）", "").replace("、", "")
                itc = it.replace("（", "").replace("）", "")
                # 直接互含
                hit = (npc in itc or itc in npc)
                # 别名命中: 项目名词 → 产品同义词
                for src in (npc,):
                    for al in ALIAS.get(src, ()):
                        if al in itc:
                            hit = True
                            break
                if hit:
                    keep.add(it)
                    break
        if keep:  # 命中≥1才限定 (避免误伤)
            items = [it for it in items if it in keep]
    # 2) 从设备名提取产品/工段 (设备名常含产品线, 如'氯化钙生产线')
    #    注意: 排除 仓库/车间/机房/办公/辅助 等非生产工段
    _NON_PRODUCT = ("仓库", "车间", "机房", "办公室", "化验室", "实验室", "配电", "辅助",
                    "预处理", "公辅", "污水处理", "废气", "废水", "储运", "包装", "公用")
    if len(items) < 8:
        eqs = proj_data.get("equipment", []) or []
        for e in eqs:
            name = str(e).split("|")[0].strip()
            # 跳过明显的非生产设备 (仓库/车间等不含产品特征)
            if any(np in name for np in _NON_PRODUCT):
                continue
            m = re.match(r"^(.{2,20}?)(?:生产线|装置|系统|工段|机组)", name)
            if m:
                prod = m.group(1).strip()
                # 排除与已有产品名包含重复 (如已有'液体氯化钙', 设备名'氯化钙生产线'不再加)
                if prod and len(prod) >= 2 and prod not in seen and \
                        not any(prod in x or x in prod for x in seen):
                    items.append(prod)
                    seen.add(prod)
    # 3) 从工艺文本补充 ('- 车间 X | 工序 Y' 里的 X 工段名)
    if len(items) < 4:
        for ln in (proj_data.get("process_text") or "").splitlines():
            m = re.match(r"- 车间\s*(\S+)", ln.strip())
            if m and m.group(1) not in seen and len(m.group(1)) >= 2:
                items.append(m.group(1))
                seen.add(m.group(1))
    # 去重保序, 最多 8 个 (控制规模)
    items = list(dict.fromkeys(items))[:8]
    out = []
    # 数据驱动三级: 3.5.x 产品工艺
    for i, name in enumerate(items, 1):
        out.append((f"3.5.{i}", f"{name}{DATA3['3.5']['suffix']}"))
    # 固定尾三级: 生产辅助工序(原报告通用规律: 长兴3.5.2/新泰无但5.1.1有) + 生产工艺评价
    # 辅助工序=条件单元: hazard_grid 评价单元或设备/工艺含辅助系统时生成 (不写死行业)
    tail_idx = len(items) + 1
    _AUX_KWS = ("公用", "辅助", "污水", "废水", "废气", "储运", "储罐区", "锅炉", "制冷", "供热",
                "供气", "配电", "化验", "检维修", "压缩", "冷却", "空压", "固废")
    aux_txt = " ".join(str(x) for x in (proj_data.get("equipment") or [])) + \
              (proj_data.get("process_text") or "")
    for g in (proj_data.get("hazard_grid") or []):
        if isinstance(g, dict):
            aux_txt += " " + str(g.get("unit") or "")
    if any(k in aux_txt for k in _AUX_KWS):
        out.append((f"3.5.{tail_idx}", "生产辅助工序"))
        tail_idx += 1
    out.append((f"3.5.{tail_idx}", DATA3["3.5"]["tail"]))
    # 数据驱动四级: 5.1.1.x 产品/工段
    for i, name in enumerate(items, 1):
        out.append((f"5.1.1.{i}", name))
    # 固定尾四级: 生产辅助工序 (原报告通用规律: 长兴5.1.1.2 生产辅助工序 / 新泰5.1.1.4 公用及辅助设施)
    if any(k in aux_txt for k in _AUX_KWS):
        out.append((f"5.1.1.{len(items)+1}", "生产辅助工序"))
    return out


def count_units(proj_data: dict | None = None) -> int:
    """统计报告全部生成单元数 (章 + 二级 + 三级 + 固定三级尾 + 数据三级 + 数据四级)"""
    n = 0
    for ch in CHAPTERS:
        n += 1                              # 该章
        for sn, _t in SUBS.get(ch, []):
            n += 1                          # 二级
            for sub3, (parent, _t3) in SUBS3.items():
                if parent == sn:
                    n += 1                  # 三级
    if proj_data:
        n += len(_extract_product_units(proj_data))  # 数据三级(3.5.x) + 数据四级(5.1.1.x)
    return n


def all_units() -> list[tuple]:
    """返回报告全部结构单元 (key, title): 一级 + 二级 + 三级.
    数据三级(产品工艺)和数据四级(产品识别)由生成时从项目数据补充, 不在此列表."""
    units = []
    for ch in CHAPTERS:
        units.append((ch, CHAPTERS[ch]))
        for sn, t in SUBS.get(ch, []):
            units.append((sn, f"{sn} {t}"))
            for sub3, (parent, t3) in SUBS3.items():
                if parent == sn:
                    units.append((sub3, f"{sub3} {t3}"))
    return units


